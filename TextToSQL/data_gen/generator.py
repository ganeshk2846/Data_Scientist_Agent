"""Generate reproducible SQLite warehouses with realistic metadata defects."""
import argparse
import hashlib
import json
import random
import sqlite3
import tempfile
from datetime import datetime, timedelta, timezone
from typing import Protocol
from pathlib import Path
from data_gen.provenance import register_dataset
from data_gen.access import require_development_write

BASE_TABLE_COUNT = 10


class ManifestWriter:
    """Collect explicit planted facts for the scoring-only manifest."""
    def __init__(self, snapshot_id: str, seed: int, split: str):
        self.data = {"snapshot_id": snapshot_id, "seed": seed, "generator_version": "5",
                     "split": split, "anomalies": [], "drivers": [], "confounders": [],
                     "negative_controls": [], "churn_process": [], "sql_traps": []}

    def record(self, section: str, fact: dict) -> None:
        if section not in {"anomalies", "drivers", "confounders", "negative_controls", "churn_process", "sql_traps"}:
            raise ValueError(f"unsupported ground-truth section: {section}")
        self.data[section].append(fact)


class PlantPlugin(Protocol):
    name: str
    def inject(self, warehouse: sqlite3.Connection, rng: random.Random, manifest: ManifestWriter) -> None: ...


def generate(path: str | Path, table_count: int = 50, seed: int = 7, injection=None,
             snapshot: str = "development", injection_config: dict | None = None,
             *, plugins: list[PlantPlugin] | None = None, truth_dir: str | Path | None = None) -> dict:
    require_development_write("synthetic dataset or ground-truth generation")
    if table_count not in (50, 200, 500):
        raise ValueError("table_count must be one of 50, 200 or 500")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise FileExistsError(f"Refusing to overwrite existing warehouse: {path}")
    public_manifest_path = path.with_suffix(".manifest.json")
    if public_manifest_path.exists():
        raise FileExistsError(f"Refusing to overwrite existing manifest: {public_manifest_path}")
    provenance_path = path.with_suffix(".provenance.json")
    if provenance_path.exists():
        raise FileExistsError(f"Refusing to overwrite existing provenance: {provenance_path}")
    rng = random.Random(seed)
    anomaly_multiplier = float((injection_config or {}).get("north_june_revenue_multiplier", 1.8))
    if anomaly_multiplier <= 0:
        raise ValueError("north_june_revenue_multiplier must be positive")
    split = "build" if snapshot == "development" else "heldout" if snapshot == "held-out" else None
    if split is None:
        raise ValueError("snapshot must be development or held-out")
    snapshot_id = f"{snapshot}-{table_count}-{seed}"
    truth = ManifestWriter(snapshot_id, seed, split)
    plugin_order = sorted(plugins or [], key=lambda plugin: plugin.name)
    con = sqlite3.connect(path)
    try:
        # This file is disposable generated input; avoid per-statement fsync cost.
        con.execute("PRAGMA journal_mode = OFF")
        con.execute("PRAGMA synchronous = OFF")
        con.execute("PRAGMA foreign_keys = ON")
        con.executescript("""
            CREATE TABLE cstmr_dim (cstmr_id INTEGER PRIMARY KEY, full_name TEXT, email_address TEXT, region TEXT, created_at TEXT);
            CREATE TABLE ord_hdr (ord_key INTEGER PRIMARY KEY, cstmr_id INTEGER, order_date TEXT, status TEXT, amount REAL, deleted_at TEXT, is_test INTEGER);
            CREATE TABLE item_dim (item_key INTEGER PRIMARY KEY, item_name TEXT, category TEXT);
            CREATE TABLE ord_line (line_key INTEGER PRIMARY KEY, ord_key INTEGER, item_key INTEGER, quantity INTEGER, unit_price REAL);
            CREATE TABLE cstmr_archive (cstmr_id INTEGER, full_name TEXT, region TEXT);
        """)
        # Fixed epoch keeps generated bytes reproducible for a given seed/config.
        now = datetime(2025, 1, 1, tzinfo=timezone.utc)
        regions = ["North", "South", "West", "East", "N", "south "]
        con.executemany("INSERT INTO cstmr_dim VALUES (?, ?, ?, ?, ?)", [(i, f"Customer {i}", f"customer{i}@example.invalid", rng.choice(regions), (now - timedelta(days=rng.randrange(1, 1000))).isoformat()) for i in range(1, 101)])
        con.executemany("INSERT INTO ord_hdr VALUES (?, ?, ?, ?, ?, ?, ?)", [(i, rng.randint(1, 100), (now - timedelta(days=rng.randrange(0, 365))).date().isoformat(), rng.choice(["paid", "open", "cancelled", "PAID "]), round(rng.uniform(10, 900), 2), "2024-01-01" if i % 37 == 0 else None, int(i % 50 == 0)) for i in range(1, 601)])
        con.executemany("INSERT INTO item_dim VALUES (?, ?, ?)", [(i, f"Item {i}", rng.choice(["food", "home", "tech"])) for i in range(1, 41)])
        con.executemany("INSERT INTO ord_line VALUES (?, ?, ?, ?, ?)", [(i, rng.randint(1, 600), rng.randint(1, 40), rng.randint(1, 8), round(rng.uniform(1, 150), 2)) for i in range(1, 1801)])
        con.executemany("INSERT INTO cstmr_archive VALUES (?, ?, ?)", [(i, f"Customer {i}", rng.choice(regions)) for i in range(1, 81)])
        con.execute("INSERT INTO cstmr_archive VALUES (1, 'Customer 1', 'legacy-duplicate')")
        con.executescript("""
            CREATE TABLE customer_merge_map (canonical_customer_id INTEGER, merged_customer_id INTEGER, reason TEXT);
            INSERT INTO customer_merge_map VALUES (1, 101, 'duplicate-account reconciliation');
            CREATE TABLE late_events (event_id INTEGER PRIMARY KEY, event_date TEXT, ingested_at TEXT, amount REAL);
            INSERT INTO late_events VALUES (1, '2024-11-30', '2025-01-03', 125.0);
            CREATE TABLE daily_snapshot (snapshot_date TEXT, value REAL, is_complete INTEGER);
            INSERT INTO daily_snapshot VALUES ('2024-12-29', 11.0, 1), ('2024-12-30', 12.0, 1), ('2024-12-31', 0.0, 0);
            CREATE TABLE monthly_kpi (month TEXT, region TEXT, revenue REAL, order_count INTEGER);
            CREATE TABLE customer_risk (customer_id INTEGER, segment TEXT, churned INTEGER, risk_score REAL);
        """)
        months = [(datetime(2023, month, 1) + timedelta(days=365 * year)).strftime("%Y-%m") for year in range(2) for month in range(1, 13)]
        kpis = []
        for month in months:
            for region in ("North", "South"):
                base = 1000.0 if region == "North" else 900.0
                anomaly = month == "2024-06" and region == "North"
                kpis.append((month, region, base * (anomaly_multiplier if anomaly else 1), 100 if anomaly else 90))
        con.executemany("INSERT INTO monthly_kpi VALUES (?, ?, ?, ?)", kpis)
        con.executemany("INSERT INTO customer_risk VALUES (?, ?, ?, ?)", [(i, "declining" if i % 10 == 0 else "steady", int(i % 10 == 0), 0.9 if i % 10 == 0 else 0.1) for i in range(1, 101)])
        for i in range(table_count - BASE_TABLE_COUNT):
            # Cryptic names and weakly related columns make retrieval/join discovery nontrivial.
            table, key = f"x{i:03x}", f"k{i:03x}"
            con.execute(f'CREATE TABLE "{table}" ("{key}" INTEGER PRIMARY KEY, "v{i:03x}" TEXT, "n{i:03x}" REAL, "updated_at" TEXT)')
            if i % 7 == 0:
                con.execute(f'INSERT INTO "{table}" VALUES (1, ?, ?, ?)', ("legacy", 1.0, "2021-01-01"))
        if injection:
            injection(con)
        for plugin in plugin_order:
            plugin.inject(con, rng, truth)
        con.commit()
    finally:
        con.close()
    database_hash = hashlib.sha256(path.read_bytes()).hexdigest()
    # Bind the private scoring manifest to the exact generated warehouse so an
    # auditor cannot accidentally validate truth against a different snapshot.
    truth.data["database_sha256"] = database_hash
    manifest = {
        "database": path.name, "database_sha256": database_hash, "seed": seed,
        "generator_version": truth.data["generator_version"],
        "table_count": table_count, "snapshot": snapshot, "snapshot_id": snapshot_id,
        "injection": getattr(injection, "__name__", None), "injection_config": injection_config or {},
        "plugins": [plugin.name for plugin in plugin_order],
        "generated_at": "2025-01-01T00:00:00+00:00",
        "planted_features": {
            "cryptic_tables": table_count - BASE_TABLE_COUNT,
            "distractor_tables": table_count - BASE_TABLE_COUNT,
            "stale_copy_rows": 80,
            "soft_deleted_orders": 600 // 37,
            "messy_region_values": ["N", "south "],
            "messy_status_value": "PAID ",
            "missing_declared_foreign_keys": True,
            "duplicate_archive_rows": 1,
            "merged_customer_cases": 1,
            "test_order_rows": 600 // 50,
            "late_event_rows": 1,
            "truncated_snapshot_rows": 1,
            "unanswerable_questions": ["What is the average customer NPS by postal code?"],
        },
    }
    truth.record("anomalies", {"anomaly_id": "north-revenue-june-2024", "metric": "revenue", "unit": {"dimension": "region", "value": "North"}, "kind": "level_shift", "start": "2024-06", "magnitude_pct": round((anomaly_multiplier - 1) * 100, 2)})
    truth.record("drivers", {"anomaly_id": "north-revenue-june-2024", "cause_kind": "segment", "cause": {"dimension": "region", "value": "North"}, "true_share": 1.0})
    truth.record("confounders", {"anomaly_id": "north-revenue-june-2024", "moves_with": {"dimension": "season", "value": "June"}, "is_cause": False})
    truth.record("negative_controls", {"control_id": "south-june-2024", "metric": "revenue", "unit": {"dimension": "region", "value": "South"}, "period": {"start": "2024-06-01", "end": "2024-07-01"}, "kind": "ordinary"})
    truth.record("churn_process", {"process_id": "decile-risk-v1", "description": "Every tenth customer is a planted churn case", "params": {"positive_rate": 0.1}, "true_risk_segments": [{"segment": "declining", "relative_risk": 9.0}], "label_table": "customer_risk"})
    truth.record("sql_traps", {"trap_id": "cancelled-orders", "kind": "cancelled_orders", "question": "What is revenue excluding cancelled and deleted orders?", "correct_result_sql": "SELECT SUM(amount) FROM ord_hdr WHERE lower(trim(status)) <> 'cancelled' AND deleted_at IS NULL AND is_test = 0", "correct_value": con_value(path, "SELECT SUM(amount) FROM ord_hdr WHERE lower(trim(status)) <> 'cancelled' AND deleted_at IS NULL AND is_test = 0")})
    truth.record("sql_traps", {"trap_id": "order-line-fanout", "kind": "fan_out", "question": "What is total order-header revenue without line-item fan-out?", "correct_result_sql": "SELECT SUM(amount) FROM ord_hdr", "correct_value": con_value(path, "SELECT SUM(amount) FROM ord_hdr")})
    truth.record("sql_traps", {"trap_id": "duplicate-customers", "kind": "duplicates", "question": "How many duplicate archive customer keys are present?", "correct_result_sql": "SELECT COUNT(*) FROM (SELECT cstmr_id FROM cstmr_archive GROUP BY cstmr_id HAVING COUNT(*) > 1)", "correct_value": con_value(path, "SELECT COUNT(*) FROM (SELECT cstmr_id FROM cstmr_archive GROUP BY cstmr_id HAVING COUNT(*) > 1)")})
    truth_root = Path(truth_dir) if truth_dir is not None else Path(tempfile.gettempdir()) / "texttosql-scoring-truth"
    truth_root.mkdir(parents=True, exist_ok=True)
    truth_path = truth_root / f"v{truth.data['generator_version']}-{snapshot_id}-{database_hash[:16]}.json"
    if truth_path.exists():
        if truth_path.read_text(encoding="utf-8") != json.dumps(truth.data, indent=2):
            raise FileExistsError(f"Refusing to overwrite existing ground truth: {truth_path}")
    else:
        truth_path.write_text(json.dumps(truth.data, indent=2), encoding="utf-8")
    public_manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    register_dataset({"name": f"TextToSQL synthetic warehouse {snapshot_id}",
                      "url": "local://TextToSQL/data_gen/generator.py",
                      "version": str(manifest["generator_version"]),
                      "licence": "synthetic data generated by local project code; no third-party records",
                      "permitted_use": "project development and evaluation", "split": snapshot,
                      "layer": "synthetic_enterprise", "source_sha256": database_hash,
                      "artifact_sha256": database_hash}, provenance_path)
    return manifest


def generate_snapshot_pair(output_dir: str | Path, *, table_count: int = 50, seed: int = 7,
                           truth_dir: str | Path | None = None) -> dict:
    """Build two non-overwriting snapshots with distinct seeds and injections."""
    root = Path(output_dir)
    build = generate(root / "build.sqlite", table_count=table_count, seed=seed,
                     snapshot="development", injection_config={"north_june_revenue_multiplier": 1.8}, truth_dir=truth_dir)
    heldout = generate(root / "heldout.sqlite", table_count=table_count, seed=seed + 1,
                       snapshot="held-out", injection_config={"north_june_revenue_multiplier": 1.6}, truth_dir=truth_dir)
    return {"build": build, "heldout": heldout}


def con_value(path: Path, query: str):
    connection = sqlite3.connect(f"file:{path.resolve().as_posix()}?mode=ro", uri=True)
    try:
        return connection.execute(query).fetchone()[0]
    finally:
        connection.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="data/generated/warehouse.sqlite")
    parser.add_argument("--tables", type=int, choices=(50, 200, 500), default=50)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--snapshot", choices=("development", "held-out"), default="development")
    args = parser.parse_args()
    print(json.dumps(generate(args.output, args.tables, args.seed, snapshot=args.snapshot), indent=2))


if __name__ == "__main__":
    main()
