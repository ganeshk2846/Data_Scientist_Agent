"""Render ``semantics/metrics.md`` from the metric registries.

    python scripts/render_semantics.py

The page is generated so it cannot drift from the definitions it describes;
a test holds the committed file equal to this output.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "backend" / "src"))

from semantic.aggregation import AggregationRegistry  # noqa: E402
from semantic.metrics_v2 import all_metrics, is_synthetic_metric  # noqa: E402

METRICS_PAGE = REPO_ROOT / "semantics" / "metrics.md"


def _sql(template: str) -> str:
    return re.sub(r"\{\{\s*(\w+)\s*\}\}", r"\1", " ".join(template.split()))


def render_metrics() -> str:
    aggregations = AggregationRegistry()
    lines = [
        "# Metrics",
        "",
        "**Generated by `scripts/render_semantics.py` from the metric registries. Do not edit by hand.**",
        "",
        "Nine governed metrics read the real Olist snapshot; seven KPIs read the",
        "synthetic layer and are always labelled synthetic. Every metric's date",
        "is bounded by the completeness rule: on the real data the last complete",
        "month is 2018-08.",
        "",
    ]
    for metric in all_metrics().metrics:
        entry = aggregations.require(metric.metric_id)
        layer = "**synthetic**" if is_synthetic_metric(metric.metric_id) else "real"
        lines += [
            f"## `{metric.metric_id}` — {metric.name}",
            "",
            f"- **Layer:** {layer}",
            f"- **Aggregation:** `{entry.aggregation}`",
            f"- **Formula:** `{_sql(metric.formula)}`",
        ]
        if entry.numerator is not None:
            lines += [
                f"- **Numerator:** `{entry.numerator.name}` = `{_sql(entry.numerator.formula)}`",
                f"- **Denominator:** `{entry.denominator.name}` = `{_sql(entry.denominator.formula)}`",
            ]
        if entry.bounds is not None:
            lines.append(f"- **Bounds:** {entry.bounds[0]:g} to {entry.bounds[1]:g}")
        lines += [
            f"- **Base table:** `{metric.base_table}`; date `{metric.date_column}`",
            f"- **Required filters:** {', '.join(f'`{_sql(f)}`' for f in metric.required_filters) or 'none'}",
            f"- **Dimensions:** {', '.join(f'`{d.name}`' for d in metric.allowed_dimensions) or 'none'}",
            f"- **Synonyms:** {', '.join(metric.synonyms)}",
        ]
        lines += [f"- **Caveat:** {caveat}" for caveat in metric.caveats]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    METRICS_PAGE.parent.mkdir(parents=True, exist_ok=True)
    METRICS_PAGE.write_text(render_metrics(), encoding="utf-8")
    print(METRICS_PAGE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
