import { Check, Copy } from 'lucide-react';
import { useCallback, useState } from 'react';

import { SqlBlock } from './SqlBlock';
import { Tag } from '@/components/briefing/StatusBadge';
import { Card, SectionLabel } from '@/components/ui/Card';
import { Collapsible } from '@/components/ui/Collapsible';
import { cx } from '@/lib/cx';
import { formatDuration, formatNumber } from '@/lib/format';
import type { EnvelopeQueryRecord, SqlOrigin } from '@/types/envelope';

const ORIGIN_NOTE: Record<SqlOrigin, string> = {
  compiler: 'Compiled from the governed metric registry — no model involved.',
  generator: 'Generated by the deterministic CTE generator.',
  repair: 'Produced by the bounded self-repair loop.',
};

function CopyButton({ sql }: { sql: string }) {
  const [copied, setCopied] = useState(false);

  const copy = useCallback(() => {
    void navigator.clipboard.writeText(sql).then(
      () => {
        setCopied(true);
        window.setTimeout(() => setCopied(false), 1_800);
      },
      () => setCopied(false),
    );
  }, [sql]);

  return (
    <button
      type="button"
      onClick={copy}
      aria-label={copied ? 'SQL copied' : 'Copy SQL'}
      className={cx(
        'inline-flex items-center gap-1.5 rounded-sm border px-2.5 py-1 text-[0.6875rem]',
        'transition-colors duration-micro ease-editorial',
        copied
          ? 'border-gold text-gold'
          : 'border-hairline-strong text-ink-faint hover:border-gold hover:text-gold',
      )}
    >
      {copied ? (
        <Check size={11} strokeWidth={2.5} aria-hidden />
      ) : (
        <Copy size={11} strokeWidth={2} aria-hidden />
      )}
      {copied ? 'copied' : 'copy'}
    </button>
  );
}

interface QueryListProps {
  queries: readonly EnvelopeQueryRecord[];
  /**
   * `_queries` stamps every record with the run's single candidate origin, so
   * the badge belongs here once, not on each card.
   */
  origin: SqlOrigin | null;
}

export function QueryList({ queries, origin }: QueryListProps) {
  if (queries.length === 0) return null;

  return (
    <section>
      <div className="flex flex-wrap items-center justify-between gap-x-4 gap-y-2">
        <SectionLabel>
          SQL
          <span aria-hidden className="mx-2 text-ink-faint/50">
            ·
          </span>
          <span className="normal-case tracking-normal">
            {queries.length} quer{queries.length === 1 ? 'y' : 'ies'}
          </span>
        </SectionLabel>

        {origin ? (
          <span className="flex items-center gap-2.5">
            <Tag tone="gold" title={ORIGIN_NOTE[origin]}>
              {origin}
            </Tag>
            <span className="hidden text-[0.6875rem] text-ink-faint sm:block">
              {ORIGIN_NOTE[origin]}
            </span>
          </span>
        ) : null}
      </div>

      <div className="mt-4 space-y-3">
        {queries.map((query) => (
          <Card key={query.query_id} className="px-5 py-4">
            <Collapsible
              summary={
                <span className="flex flex-wrap items-center gap-x-4 gap-y-1.5">
                  <span className="font-mono text-small text-ink">{query.query_id}</span>
                  <Tag tone={query.status === 'ok' ? 'sage' : 'terracotta'}>
                    {query.status}
                  </Tag>
                  <span className="font-mono text-[0.6875rem] tabular-nums text-ink-faint">
                    {formatDuration(query.duration_ms)}
                  </span>
                  {query.rows_scanned != null ? (
                    <span className="text-[0.6875rem] tabular-nums text-ink-faint">
                      {formatNumber(query.rows_scanned)} rows scanned
                    </span>
                  ) : null}
                  {query.est_cost != null ? (
                    <span className="text-[0.6875rem] tabular-nums text-ink-faint">
                      cost {formatNumber(query.est_cost, 2)}
                    </span>
                  ) : null}
                  {query.validation_mode ? (
                    <span className="text-[0.6875rem] text-ink-faint">
                      {query.validation_mode}
                    </span>
                  ) : null}
                  {query.repair_of ? (
                    <span className="font-mono text-[0.6875rem] text-ink-faint">
                      repair of {query.repair_of}
                    </span>
                  ) : null}
                </span>
              }
            >
              <div className="mt-4">
                <div className="mb-2.5 flex justify-end">
                  <CopyButton sql={query.sql} />
                </div>
                <SqlBlock sql={query.sql} />
              </div>
            </Collapsible>
          </Card>
        ))}
      </div>
    </section>
  );
}
