const ORIGIN_NOTE: Record<SqlOrigin, string> = {
  compiler: 'Compiled from the governed metric registry — no model involved',
  generator: 'Generated by the deterministic CTE generator',
  repair: 'Produced by the bounded self-repair loop',
};

export function CopyButton({
  text,
  label = 'SQL',
  className,
}: {
  text: string;
  label?: string;
  className?: string;
}) {
  const [copied, setCopied] = useState(false);

  const copy = useCallback(() => {
    void navigator.clipboard.writeText(text).then(
      () => {
        setCopied(true);
        window.setTimeout(() => setCopied(false), 1_900);
      },
      () => setCopied(false),
    );
  }, [text]);

  return (
    <button
      type="button"
      onClick={copy}
      aria-label={copied ? `${label} copied` : `Copy ${label}`}
      className={cx(
        'inline-flex items-center gap-1.5 rounded-sm border px-2.5 py-1',
        'text-[0.6875rem] transition-colors duration-micro ease-editorial',
        copied
          ? 'border-accent text-accent-ink'
          : 'border-hairline text-ink-faint hover:border-hairline-strong hover:text-ink',
        className,
      )}
    >
      {/* The tick draws itself on; a swap would feel like a glitch. */}
      <span className="relative grid h-3 w-3 place-items-center">
        <Copy
          size={11}
          strokeWidth={1.5}
          aria-hidden
          className={cx(
            'absolute transition-all duration-200 ease-editorial',
            copied ? 'scale-75 opacity-0' : 'scale-100 opacity-100',
          )}
        />
        <Check
          size={11}
          strokeWidth={1.5}
          aria-hidden
          className={cx(
            'absolute transition-all duration-300 ease-editorial',
            copied ? 'scale-100 opacity-100' : 'scale-50 opacity-0',
          )}
        />
      </span>
      {copied ? 'copied' : 'copy'}
    </button>
  );
}

interface QueryListProps {
  queries: readonly EnvelopeQueryRecord[];
  claims: readonly LedgerClaim[];
  /**
   * `_queries` stamps every record with the run's single candidate origin, so
   * the badge belongs at run level, once — not on each card.
   */
  origin: SqlOrigin | null;
  /** Rendered as the section's own heading, so it can read as "How …". */
  heading?: string;
}

/**
 * "How this was computed" — the SQL, as a first-class part of the briefing
 * rather than an appendix. Expanded by default: the whole promise of this
 * product is that you can check the arithmetic.
 */
export function QueryList({ queries, claims, origin, heading }: QueryListProps) {
  if (queries.length === 0) return null;
  const validationMode = queries[0]?.validation_mode ?? null;

  return (
    <section data-print="flow">
      <div className="flex flex-wrap items-baseline justify-between gap-x-6 gap-y-3">
        <div>
          <SectionLabel>How this was computed</SectionLabel>
          {heading ? (
            <h2 className="mt-2.5 font-serif text-[1.375rem] leading-snug text-ink">
              {heading}
            </h2>
          ) : null}
        </div>

        <div className="flex flex-wrap items-center gap-2">
          {origin ? (
            <Tag title={ORIGIN_NOTE[origin]}>
              {origin}
            </Tag>
          ) : null}
          {validationMode ? <Tag>{validationMode}</Tag> : null}
          <Tag>
            {queries.length} quer{queries.length === 1 ? 'y' : 'ies'}
          </Tag>
        </div>
      </div>

      {origin ? (
        <p className="mt-3 max-w-prose text-[0.8125rem] leading-relaxed text-ink-faint">
          {ORIGIN_NOTE[origin]}.
        </p>
      ) : null}

      <div className="mt-6 space-y-4">
        {queries.map((query) => (
          <QueryCard
            key={query.query_id}
            query={query}
            claims={claims.filter((claim) => claim.source.id.includes(query.query_id))}
          />
        ))}
      </div>
    </section>
  );
}

function QueryCard({
  query,
  claims,
}: {
  query: EnvelopeQueryRecord;
  claims: readonly LedgerClaim[];
}) {
  const lineage = useLineage();
  const lit = lineage.isSourceLit(query.query_id);
  const handlers = useLineageHandlers({
    claimIds: claims.map((claim) => claim.claim_id),
    sourceIds: [query.query_id],
  });

  const stats: readonly (readonly [string, string])[] = [
    ['duration', formatDuration(query.duration_ms)],
    ...(query.rows_scanned != null
      ? ([['rows scanned', formatNumber(query.rows_scanned)]] as const)
      : []),
    ...(query.est_cost != null
      ? ([['est. cost', formatNumber(query.est_cost, 2)]] as const)
      : []),
    ...(query.repair_of ? ([['repair of', query.repair_of]] as const) : []),
  ];

  return (
    <Card
      tone="flat"
      className={cx(
        'edge-light scroll-mt-20 overflow-hidden transition-[border-color,box-shadow] duration-micro ease-editorial',
        lit && 'border-accent shadow-lifted',
      )}
      {...handlers}
    >
      <div
        id={`query-${query.query_id}`}
        className="flex flex-wrap items-center gap-x-5 gap-y-2.5 border-b border-hairline px-5 py-3"
      >
        <span className="flex items-center gap-2">
          <Database
            size={12}
            strokeWidth={1.5}
            aria-hidden
            className={lit ? 'text-accent-ink' : 'text-ink-faint'}
          />
          <span
            className={cx(
              'font-mono text-[0.8125rem] transition-colors duration-micro',
              lit ? 'text-accent-ink' : 'text-ink',
            )}
          >
            {query.query_id}
          </span>
        </span>

        <Tag tone={query.status === 'ok' ? 'sage' : 'terracotta'}>{query.status}</Tag>

        <dl className="flex flex-wrap items-baseline gap-x-5 gap-y-1">
          {stats.map(([label, value]) => (
            <div key={label} className="flex items-baseline gap-1.5">
              <dt className="text-micro uppercase tracking-label text-ink-faint">
                {label}
              </dt>
              <dd className="font-mono text-[0.75rem] tabular-nums text-ink-muted">
                {value}
              </dd>
            </div>
          ))}
        </dl>

        {claims.length > 0 ? (
          <span className="flex items-baseline gap-2">
            <span className="text-micro uppercase tracking-label text-ink-faint">
              {claims.length === 1 ? 'claim' : 'claims'}
            </span>
            {claims.map((claim) => (
              <span
                key={claim.claim_id}
                className={cx(
                  'font-mono text-[0.75rem] transition-colors duration-micro',
                  lineage.isClaimLit(claim.claim_id) ? 'text-accent-ink' : 'text-ink-muted',
                )}
              >
                {claim.claim_id}
              </span>
            ))}
          </span>
        ) : null}

        <div className="ml-auto flex items-center gap-2" data-print="hide">
          <CopyButton text={query.sql} />
        </div>
      </div>

      <div className="p-4">
        {/* Named per query, so several SQL regions on one page stay distinct landmarks. */}
        <SqlBlock sql={query.sql} label={`SQL for ${query.query_id}`} />
      </div>
    </Card>
  );
}

/** The read-only guarantee, stated where the SQL is. */
export function ReadOnlyNote() {
  return (
    <p className="flex items-center gap-2 text-[0.6875rem] text-ink-faint">
      <ShieldCheck size={12} strokeWidth={1.5} aria-hidden className="text-sage" />
      Executed through a read-only gateway. Writes are rejected at the driver.
    </p>
  );
}
